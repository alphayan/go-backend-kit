func TestGeneratedProjectCompilesAndRunsContract(t *testing.T) {
	ctx := context.Background()
	root := filepath.Join(t.TempDir(), "task-api")
	kitRoot, err := filepath.Abs(filepath.Join("..", ".."))
	if err != nil {
		t.Fatal(err)
	}
	g := generate.Generator{Version: "v0.1.0", DevelopmentReplace: kitRoot}
	if err := g.New(ctx, root, "example.com/task-api"); err != nil {
		t.Fatal(err)
	}
	source := filepath.Join(t.TempDir(), "task.yaml")
	rich := strings.Replace(taskYAML, "max_length: 200", "max_length: 200\n    unique: true", 1)
	if err := os.WriteFile(source, []byte(rich), 0o600); err != nil {
		t.Fatal(err)
	}
	run(t, root, "go", "tool", "gobackend", "add", source)
	run(t, root, "go", "mod", "tidy", "-diff")
	allTypes := filepath.Join(t.TempDir(), "all_types.yaml")
	if err := os.WriteFile(allTypes, []byte(allTypesYAML), 0o600); err != nil {
		t.Fatal(err)
	}
	run(t, root, "go", "tool", "gobackend", "add", allTypes)
	baseOnly := filepath.Join(t.TempDir(), "base_only.yaml")
	if err := os.WriteFile(baseOnly, []byte("schema_version: 1\nname: BaseOnly\ntable: base_only\nroute: /base-only\nfields: []\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	run(t, root, "go", "tool", "gobackend", "add", baseOnly)
	run(t, root, "go", "tool", "gobackend", "add", filepath.Join(kitRoot, "examples", "defaults.yaml"))
	constrained := filepath.Join(t.TempDir(), "tiny.yaml")
	if err := os.WriteFile(constrained, []byte(constrainedYAML), 0o600); err != nil {
		t.Fatal(err)
	}
	run(t, root, "go", "tool", "gobackend", "add", constrained)
	run(t, root, "go", "tool", "gobackend", "generate")
	run(t, root, "go", "tool", "gobackend", "check")
	run(t, root, "go", "tool", "gorm", "--help")
	run(t, root, "go", "test", "./...")
}

func run(t *testing.T, dir, name string, args ...string) {
	t.Helper()
	command := exec.Command(name, args...)
	command.Dir = dir
	output, err := command.CombinedOutput()
	if err != nil {
		t.Fatalf("%s %s: %v\n%s", name, strings.Join(args, " "), err, output)
	}
}

