func TestGeneratePreservesUnownedGeneratedFiles(t *testing.T) {
	root := filepath.Join(t.TempDir(), "api")
	g := testGenerator(t)
	if err := g.New(t.Context(), root, "example.com/api"); err != nil {
		t.Fatal(err)
	}

	const content = "// Code generated by 'gorm.io/cli/gorm'. DO NOT EDIT.\n\npackage generated\n"
	paths := []string{
		"internal/custom/query_gen.go",
		"internal/resources/custom/gormgen/query_gen.go",
		".worktrees/other/internal/resources/task/gormgen/query_gen.go",
	}
	for _, name := range paths {
		path := filepath.Join(root, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}

	if err := g.Generate(t.Context(), root); err != nil {
		t.Fatal(err)
	}
	for _, name := range paths {
		data, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(name)))
		if err != nil {
			t.Errorf("unowned generated file %s was removed: %v", name, err)
			continue
		}
		if string(data) != content {
			t.Errorf("unowned generated file %s changed", name)
		}
	}
}

