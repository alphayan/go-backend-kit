func TestNewAddGenerateAndCheck(t *testing.T) {
	ctx := context.Background()
	root := filepath.Join(t.TempDir(), "task-api")
	g := testGenerator(t)
	if err := g.New(ctx, root, "example.com/task-api"); err != nil {
		t.Fatalf("New() error = %v", err)
	}
	source := filepath.Join(t.TempDir(), "task.yaml")
	rich := strings.Replace(taskYAML, "max_length: 200", "max_length: 200\n    unique: true", 1)
	if err := os.WriteFile(source, []byte(rich), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := g.Add(ctx, root, source); err != nil {
		t.Fatalf("Add() error = %v", err)
	}
	if err := g.Check(ctx, root); err != nil {
		t.Fatalf("Check() error = %v", err)
	}

	wantFiles := []string{
		".env.example",
		".gitignore",
		".github/workflows/ci.yml",
		"cmd/api/main.go",
		"internal/platform/config/config_test.go",
		"internal/platform/database/database_test.go",
		"migrations/.gitkeep",
		"internal/resources/task/model_gen.go",
		"internal/resources/task/dto_gen.go",
		"internal/resources/task/gormgen/query_gen.go",
		"internal/resources/task/store_gen.go",
		"internal/resources/task/http_gen.go",
		"internal/resources/task/contract_gen_test.go",
		"internal/generated/register_gen.go",
		"openapi/openapi_gen.json",
		"tools/gormschema/main_gen.go",
	}
	for _, name := range wantFiles {
		if _, err := os.Stat(filepath.Join(root, filepath.FromSlash(name))); err != nil {
			t.Errorf("generated file %s: %v", name, err)
		}
	}
	obsoleteFiles := []string{
		"internal/resources/task/repository_gen.go",
		"internal/resources/task/service_gen.go",
		"internal/resources/task/handler_gen.go",
		"internal/resources/task/routes_gen.go",
		"internal/resources/task/custom.go",
		"internal/platform/repository/repository.go",
	}
	for _, name := range obsoleteFiles {
		if _, err := os.Stat(filepath.Join(root, filepath.FromSlash(name))); !errors.Is(err, os.ErrNotExist) {
			t.Errorf("obsolete generated file %s still exists: %v", name, err)
		}
	}
	helper, err := os.ReadFile(filepath.Join(root, "internal", "resources", "task", "gormgen", "query_gen.go"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(helper), "Code generated by 'gorm.io/cli/gorm'") {
		t.Fatal("field helpers were not produced by the official GORM CLI")
	}
	storeData, err := os.ReadFile(filepath.Join(root, "internal/resources/task/store_gen.go"))
	if err != nil {
		t.Fatal(err)
	}
	storeSource := string(storeData)
	for _, required := range []string{
		"type store struct",
		"clause.Eq{",
		"Column: gormgen.Task.Done.Column()",
		"Value:",
		"gormgen.Task.Done.Asc()",
		"func (s store) create(",
		"func (s store) update(",
		"func translateDatabaseError(",
	} {
		if !strings.Contains(storeSource, required) {
			t.Errorf("generated store missing %q", required)
		}
	}

	dtoData, err := os.ReadFile(filepath.Join(root, "internal/resources/task/dto_gen.go"))
	if err != nil {
		t.Fatal(err)
	}
	for _, required := range []string{
		"func createValues(input CreateTaskInput)",
		"func updateValues(input UpdateTaskInput)",
	} {
		if !strings.Contains(string(dtoData), required) {
			t.Errorf("generated DTO helpers missing %q", required)
		}
	}

	httpData, err := os.ReadFile(filepath.Join(root, "internal/resources/task/http_gen.go"))
	if err != nil {
		t.Fatal(err)
	}
	httpSource := string(httpData)
	for _, required := range []string{
		"type handler struct",
		"h := handler{store: store{db: db}}",
		"func Register(group *echo.Group, db *gorm.DB)",
	} {
		if !strings.Contains(httpSource, required) {
			t.Errorf("generated HTTP resource missing %q", required)
		}
	}

	combined := storeSource + "\n" + httpSource
	for _, forbidden := range []string{
		"type Repository interface",
		"type Service interface",
		"Base[",
		"NewHandler(",
		"NewService(",
		"NewRepository(",
	} {
		if strings.Contains(combined, forbidden) {
			t.Errorf("generated resource retains speculative abstraction %q", forbidden)
		}
	}
	ci, err := os.ReadFile(filepath.Join(root, ".github", "workflows", "ci.yml"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(ci), "schema diff --env ci --from env://url --to env://src --exclude atlas_schema_revisions --format '{{ sql . \"  \" }}'") {
		t.Fatal("generated CI does not check migration/schema drift")
	}
	moduleFile, err := os.ReadFile(filepath.Join(root, "go.mod"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(moduleFile), "go 1.26.4\n\ntoolchain go1.26.5\n") {
		t.Fatal("generated go.mod does not separate the Go minimum from the preferred toolchain")
	}
	if strings.Contains(string(ci), "migrate lint") {
		t.Fatal("generated CI promises Atlas linting that Community edition does not provide")
	}
	if !strings.Contains(string(ci), "migrate apply --env ci") ||
		!strings.Contains(string(ci), "schema diff --env ci --from env://url --to env://src") {
		t.Fatal("generated CI does not apply and compare versioned migrations")
	}
	makefile, err := os.ReadFile(filepath.Join(root, "Makefile"))
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(makefile), "migrate-lint") {
		t.Fatal("generated Makefile exposes unsupported Atlas Community linting")
	}

	handwritten := filepath.Join(root, "internal/resources/task/rules.go")
	const handwrittenSource = "package task\n\nconst HandwrittenRule = true\n"
	if err := os.WriteFile(handwritten, []byte(handwrittenSource), 0o644); err != nil {
		t.Fatal(err)
	}
	before := snapshot(t, root)
	if err := g.Generate(ctx, root); err != nil {
		t.Fatalf("second Generate() error = %v", err)
	}
	after := snapshot(t, root)
	if before != after {
		t.Fatal("second generation changed the project")
	}
	data, err := os.ReadFile(handwritten)
	if err != nil {
		t.Fatal(err)
	}
	if string(data) != handwrittenSource {
		t.Fatalf("generation changed handwritten source: %q", data)
	}
	if err := os.WriteFile(filepath.Join(root, "internal", "resources", "task", "gormgen", "query_gen.go"), append(helper, '\n'), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := g.Check(ctx, root); err == nil || !strings.Contains(err.Error(), "gormgen/query_gen.go") {
		t.Fatalf("Check() did not report GORM CLI helper drift: %v", err)
	}
}

